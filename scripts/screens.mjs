import { chromium } from 'playwright-core';
const out = process.argv[2] ?? '.';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
page.on('pageerror', (e) => console.log(`[pageerror] ${e.message}`));
page.on('console', (m) => { if (m.type() === 'error') console.log(`[console] ${m.text()}`); });
await page.goto(`http://127.0.0.1:${process.env.PORT ?? 5391}/`, { waitUntil: 'networkidle' });
await page.waitForFunction(() => window.app);
await page.evaluate(() => { const s = window.app.save; s.money = 4321; s.cleared.viridian = 1; s.achievements['first-run'] = 1; s.lines.push('eevee', 'gastly'); s.shinyUnlocked.push('charmander'); s.friendship.charmander = 650; s.movesSeen.charmander = ['scratch', 'dragon-rage', 'fire-spin', 'flamethrower']; window.app.persist(); window.app.goTitle(); });
await page.waitForTimeout(1200);
const go = async (name, file) => { await page.getByRole('button', { name }).first().click(); await page.waitForTimeout(700); await page.screenshot({ path: `${out}/${file}` }); await page.keyboard.press('Escape'); await page.waitForTimeout(300); };
await go(/Mart/, 's1-shop.png');
await go(/Achievements/, 's2-ach.png');
await page.getByRole('button', { name: /Pok.dex/ }).click(); await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/s3-dex.png` });
await page.getByRole('button', { name: 'Moves' }).click(); await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/s4-moves.png` });
await page.keyboard.press('Escape'); await page.waitForTimeout(300);
await go('Options', 's5-options.png');
await go('Credits', 's6-credits.png');
await page.getByRole('button', { name: 'Play' }).click(); await page.waitForTimeout(300);
await page.locator('.mon').nth(1).click(); await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/s7-select-shiny.png` });
await page.getByRole('button', { name: 'Choose!' }).click(); await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/s8-stage.png` });
await browser.close();
console.log('ok');
